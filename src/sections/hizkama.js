function controlFormAccess() {
try {
var email = (localStorage.getItem('iif-user-email') || '').trim().toLowerCase();
var ownerEmail = (window.IIF_CONFIG && window.IIF_CONFIG.ownerEmail) ? window.IIF_CONFIG.ownerEmail.toLowerCase() : 'talalkenani@gmail.com';
var isLoggedIn = localStorage.getItem('iif-logged-in') === '1';
var isOwner = isLoggedIn && email === ownerEmail;
// All input and select elements in the governance form
var formElements = document.querySelectorAll('#company-governance-form input, #company-governance-form select, #governance-submit-btn');
formElements.forEach(function (element) {
if (isOwner) {
// Enable for owner
element.removeAttribute('readonly');
element.removeAttribute('disabled');
element.style.background = '';
element.style.opacity = '1';
} else {
// Disable for non-owners
if (element.type === 'file') {
element.setAttribute('disabled', 'disabled');
} else {
element.setAttribute('readonly', 'readonly');
}
element.style.background = 'var(--color-surface-subtle)';
element.style.opacity = '0.7';
}
});
} catch (e) { }
}
